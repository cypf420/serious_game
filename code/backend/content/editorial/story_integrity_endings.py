def apply_endings(document: dict) -> dict:
    """Copy a baseline/current document, editing only registered text leaves.

    No package registration or dependency on the main copy module. Exact
    superseded paragraphs may be checked against the approved source registry.
    Already-applied clauses are accepted; unfamiliar clauses raise a drift error.
    Predicate values and ordering are never read as instructions to change them.
    """
    result = deepcopy(document)
    for collection, id_key in (('main_endings', 'ending_id'), ('sub_endings', 'sub_ending_id')):
        for row in result[collection]:
            short_id = row[id_key].removeprefix('ending_')
            text = row['text']
            prefixes = _OMIT_PARAGRAPHS.get(short_id, ())
            if prefixes:
                text = '\n\n'.join(p for p in text.split('\n\n') if not p.startswith(prefixes))
            for before, after in _PATCHES.get(short_id, ()):
                # 16 accepts the exact candidate-08 clause as well as baseline.
                if isinstance(before, tuple):
                    before = next((source for source in before if source in text), before[0])
                # Check the complete approved replacement first: some new clauses
                # contain the old words (e.g. scoped "this batch's last signature").
                if after in text and before in after:
                    continue
                if before in text:
                    text = text.replace(before, after)
                elif after not in text:
                    # The approved source edition replaces this entire repeated
                    # paragraph. Accept that exact paragraph, not arbitrary drift.
                    if _superseded_by_author_edition(short_id, before, text):
                        continue
                    raise ValueError(f"{row[id_key]}: reviewed clause has drifted: {before}")
            row['text'] = text
    return result


def _superseded_by_author_edition(short_id, clause, text):
    """An exact approved replacement paragraph may supersede a historical patch."""
    if short_id not in {'18','20'}:
        return False
    import json
    from content.editorial.story_author_revision import REGISTRY
    rows = json.loads(REGISTRY.read_text(encoding='utf8'))['replacements']
    bounds = (12480,12600) if short_id=='18' else (12600,12680)
    return any(bounds[0] <= row['line'] < bounds[1] and clause in row['before']
               and row['after'] in text.split('\n\n') for row in rows)


