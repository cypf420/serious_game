def ending_reviews(document: dict) -> list[dict]:
    """Return independent review metadata; do not insert it into the package.

    All 95 combinations were read with their main and appendix boundaries.
    Legal reachability remains the controller's separate witness/API evidence.
    """
    revised = apply_endings(document)
    reviews = []
    for collection, id_key in (('main_endings', 'ending_id'), ('sub_endings', 'sub_ending_id')):
        for old, new in zip(document[collection], revised[collection], strict=True):
            short_id = old[id_key].removeprefix('ending_')
            group = short_id[:2]
            fixed, axis, notes = _REVIEW_GROUPS[group]
            reason = (
                '保留原场景，逐支核对：' + '；'.join(notes)
                if collection == 'main_endings'
                else notes[ord(short_id[-1]) - ord('a')]
            )
            reviews.append({
                'ending_id': old[id_key],
                'review_id': 'ending:' + old[id_key],
                'main_ending_id': 'ending_' + group,
                'disposition': 'rewrite' if short_id in _PATCHES or short_id in _OMIT_PARAGRAPHS else 'keep',
                'reason': reason,
                'fixed_facts': fixed,
                'free_axis': axis,
                'axis_value': old.get('axis_value'),
                'ledger_boundary': '签约按实际台账；达线不保证全36户、搬迁完成或治疗完成。原件去向不抹去检测知情。',
                'source': '2026-09-08-story-integrity-design.md §8; F06-F10; original ending_rules.json',
                'evidence_level': 'editorial + pure transformation tests; not legal-route replay',
            })
    return reviews
